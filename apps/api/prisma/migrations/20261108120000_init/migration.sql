CREATE TYPE "SystemRole" AS ENUM ('SUPER_ADMIN', 'ADMIN', 'USER');
CREATE TYPE "ProjectRole" AS ENUM ('OWNER', 'MANAGER', 'MEMBER', 'VIEWER');
CREATE TYPE "ProjectStatus" AS ENUM ('PLANNED', 'ACTIVE', 'ON_HOLD', 'COMPLETED', 'ARCHIVED');
CREATE TYPE "Priority" AS ENUM ('LOW', 'NORMAL', 'HIGH', 'CRITICAL');
CREATE TYPE "NodeType" AS ENUM ('NOTE', 'TEXT', 'SHAPE', 'TASK', 'IMAGE', 'GROUP');
CREATE TABLE "User" (
 "id" UUID PRIMARY KEY, "username" VARCHAR(64) NOT NULL UNIQUE, "fullName" VARCHAR(200) NOT NULL,
 "passwordHash" TEXT NOT NULL, "systemRole" "SystemRole" NOT NULL DEFAULT 'USER',
 "isActive" BOOLEAN NOT NULL DEFAULT true, "createdAt" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 "updatedAt" TIMESTAMPTZ NOT NULL
);
CREATE TABLE "Session" (
 "id" UUID PRIMARY KEY, "tokenHash" TEXT NOT NULL UNIQUE,"userId" UUID NOT NULL REFERENCES "User"("id") ON DELETE CASCADE ON UPDATE CASCADE,
 "expiresAt" TIMESTAMPTZ NOT NULL,"revokedAt" TIMESTAMPTZ,"createdAt" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX "Session_userId_expiresAt_idx" ON "Session"("userId","expiresAt");
CREATE TABLE "Project" (
 "id" UUID PRIMARY KEY,"code" VARCHAR(24) NOT NULL UNIQUE,"name" VARCHAR(200) NOT NULL,"description" TEXT NOT NULL DEFAULT '',
 "status" "ProjectStatus" NOT NULL DEFAULT 'ACTIVE',"ownerId" UUID NOT NULL REFERENCES "User"("id") ON DELETE RESTRICT ON UPDATE CASCADE,
 "createdAt" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,"updatedAt" TIMESTAMPTZ NOT NULL
);
CREATE TABLE "ProjectMember" (
 "projectId" UUID NOT NULL REFERENCES "Project"("id") ON DELETE CASCADE ON UPDATE CASCADE,
 "userId" UUID NOT NULL REFERENCES "User"("id") ON DELETE CASCADE ON UPDATE CASCADE,
 "role" "ProjectRole" NOT NULL DEFAULT 'MEMBER',PRIMARY KEY ("projectId","userId")
);
CREATE INDEX "ProjectMember_userId_idx" ON "ProjectMember"("userId");
CREATE TABLE "KanbanColumn" (
 "id" UUID PRIMARY KEY,"projectId" UUID NOT NULL REFERENCES "Project"("id") ON DELETE CASCADE ON UPDATE CASCADE,
 "name" VARCHAR(100) NOT NULL,"position" INTEGER NOT NULL,"isTerminal" BOOLEAN NOT NULL DEFAULT false,
 CONSTRAINT "KanbanColumn_projectId_position_key" UNIQUE ("projectId","position")
);
CREATE TABLE "Task" (
 "id" UUID PRIMARY KEY,"projectId" UUID NOT NULL REFERENCES "Project"("id") ON DELETE CASCADE ON UPDATE CASCADE,
 "columnId" UUID NOT NULL REFERENCES "KanbanColumn"("id") ON DELETE RESTRICT ON UPDATE CASCADE,
 "title" VARCHAR(255) NOT NULL,"description" TEXT NOT NULL DEFAULT '',"priority" "Priority" NOT NULL DEFAULT 'NORMAL',
 "assigneeId" UUID REFERENCES "User"("id") ON DELETE SET NULL ON UPDATE CASCADE,
 "reporterId" UUID NOT NULL REFERENCES "User"("id") ON DELETE RESTRICT ON UPDATE CASCADE,
 "dueAt" TIMESTAMPTZ,"position" DOUBLE PRECISION NOT NULL DEFAULT 0,"version" INTEGER NOT NULL DEFAULT 1,
 "completedAt" TIMESTAMPTZ,"createdAt" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,"updatedAt" TIMESTAMPTZ NOT NULL
);
CREATE INDEX "Task_projectId_columnId_position_idx" ON "Task"("projectId","columnId","position");
CREATE INDEX "Task_assigneeId_dueAt_idx" ON "Task"("assigneeId","dueAt");
CREATE TABLE "Board" (
 "id" UUID PRIMARY KEY,"projectId" UUID NOT NULL REFERENCES "Project"("id") ON DELETE CASCADE ON UPDATE CASCADE,
 "name" VARCHAR(200) NOT NULL,"createdAt" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX "Board_projectId_idx" ON "Board"("projectId");
CREATE TABLE "BoardNode" (
 "id" UUID PRIMARY KEY,"boardId" UUID NOT NULL REFERENCES "Board"("id") ON DELETE CASCADE ON UPDATE CASCADE,
 "type" "NodeType" NOT NULL,"taskId" UUID,"content" TEXT NOT NULL DEFAULT '',
 "x" DOUBLE PRECISION NOT NULL DEFAULT 0,"y" DOUBLE PRECISION NOT NULL DEFAULT 0,
 "width" DOUBLE PRECISION NOT NULL DEFAULT 220,"height" DOUBLE PRECISION NOT NULL DEFAULT 120,
 "color" TEXT NOT NULL DEFAULT '#fef08a',"version" INTEGER NOT NULL DEFAULT 1
);
CREATE INDEX "BoardNode_boardId_idx" ON "BoardNode"("boardId");
CREATE TABLE "BoardEdge" (
 "id" UUID PRIMARY KEY,"boardId" UUID NOT NULL REFERENCES "Board"("id") ON DELETE CASCADE ON UPDATE CASCADE,
 "sourceId" UUID NOT NULL,"targetId" UUID NOT NULL,"label" TEXT NOT NULL DEFAULT ''
);
CREATE INDEX "BoardEdge_boardId_idx" ON "BoardEdge"("boardId");
